    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        JFileChooser fc = new JFileChooser();
        fc.showOpenDialog(fc);
        String extension = fc.getSelectedFile().getName().substring(fc.getSelectedFile().getName().lastIndexOf("."));
        if (extension.equals(".txt")){
            loadText(c_serie.extractText(fc.getSelectedFile()));
        } else {
           JOptionPane.showMessageDialog(this, "Solo se permiten archivos .txt");
        };
        
    }//GEN-LAST:event_jButton2ActionPerformed

    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
        //int[] data = {90, 34, 25, 1, 22, 11, 90, 45, 8, 9};
        int[] numbers = c_serie.readNumbers(jTextField1.getText());
        int algorithm = jComboBox2.getSelectedIndex();
        int s_speed = jComboBox4.getSelectedIndex();
        int s_order = jComboBox3.getSelectedIndex();
        int sp = 0;
        boolean order = (s_order == 0) ? true  : false;
        
        if(s_speed==0){
            sp = 100;
        } else if (s_speed==1){
            sp = 500;
        } else if (s_speed==2){
            sp = 20;
        }
        
        System.out.println(algorithm+" | "+order+" | "+sp);
        int speed = sp;
        new Thread(() -> {
            try {
                c_serie.loadSerie(numbers, algorithm, order, speed);
                loadGraph(numbers, 0, 0, 0);
                c_serie.startAlgoritm();
                System.out.println("Comparaciones: " + c_serie.getComparaciones());
                System.out.println("Intercambios:  " + c_serie.getIntercambios());
                System.out.println("Iteraciones:   " + c_serie.getIteraciones());
                jLabel11.setText(String.valueOf(c_serie.getComparaciones()));
                jLabel13.setText(String.valueOf(c_serie.getIntercambios()));
                jLabel12.setText(String.valueOf(c_serie.getIteraciones()));
            } catch (InterruptedException ex) {
                System.getLogger(MainModule.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
                ex.printStackTrace();
            }
        }).start();
    }//GEN-LAST:event_jButton4ActionPerformed

